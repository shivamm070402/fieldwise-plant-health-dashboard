import { useState } from 'react';
import { Check, Copy, Smartphone, X } from 'lucide-react';
import './mobile-access.css';

function initialMobileUrl() {
  const localHost = ['localhost', '127.0.0.1', '::1'].includes(window.location.hostname);
  if (localHost) return '';
  const url = new URL(window.location.href);
  url.hash = '#plant';
  return url.toString();
}

export default function MobileAccessModal({ open, onClose }) {
  const [url, setUrl] = useState(initialMobileUrl);
  const [copied, setCopied] = useState(false);
  const androidDownloadUrl = import.meta.env.VITE_ANDROID_DOWNLOAD_URL?.trim() || '';
  const iosDownloadUrl = import.meta.env.VITE_IOS_DOWNLOAD_URL?.trim() || '';
  const isAndroid = /android/i.test(navigator.userAgent);
  const isIos = /iPhone|iPad|iPod/i.test(navigator.userAgent);
  const appDownloadUrl = isAndroid ? androidDownloadUrl : isIos ? iosDownloadUrl : '';
  if (!open) return null;

  const normalizedUrl = url.trim();
  const validUrl = /^https?:\/\//i.test(normalizedUrl);
  const qrUrl = validUrl
    ? `https://api.qrserver.com/v1/create-qr-code/?size=260x260&margin=12&data=${encodeURIComponent(normalizedUrl)}`
    : '';

  async function copyLink() {
    try {
      await navigator.clipboard.writeText(normalizedUrl);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      setCopied(false);
    }
  }

  return <div className="mobile-access-backdrop" onMouseDown={(event) => { if (event.target === event.currentTarget) onClose(); }}>
    <section className="mobile-access-dialog" role="dialog" aria-modal="true" aria-labelledby="mobile-access-title">
      <button className="mobile-access-close" type="button" onClick={onClose} aria-label="Close mobile access"><X size={18} /></button>
      <span className="mobile-access-icon"><Smartphone size={21} /></span>
      <span className="mobile-access-eyebrow">FIELDWISE · ON YOUR PHONE</span>
      <h2 id="mobile-access-title">Take the field with you.</h2>
      <p>{isAndroid && androidDownloadUrl ? 'Download the Android app on this device.' : isIos && iosDownloadUrl ? 'Continue to the iOS app listing on this device.' : 'Scan this code with your phone camera to open the plant scanner.'} Your phone and computer must be on the same Wi-Fi for a local development site.</p>
      {appDownloadUrl && <a className="mobile-access-download" href={appDownloadUrl} target={isIos ? '_blank' : undefined} rel={isIos ? 'noreferrer' : undefined} download={isAndroid ? true : undefined}>{isAndroid ? 'Download Android APK' : 'Get the iOS app'}</a>}
      {qrUrl ? <img className="mobile-access-qr" src={qrUrl} alt="QR code to open the Fieldwise plant scanner on your phone" referrerPolicy="no-referrer" /> : <div className="mobile-access-empty"><Smartphone size={26} /><span>Enter your computer’s Wi-Fi address to make the QR code.</span></div>}
      <label className="mobile-access-url-label" htmlFor="mobile-access-url">PHONE-ACCESSIBLE WEBSITE ADDRESS</label>
      <div className="mobile-access-url-row"><input id="mobile-access-url" type="url" value={url} onChange={(event) => setUrl(event.target.value)} placeholder={`http://192.168.1.25:${window.location.port || '5173'}/#plant`} /><button type="button" onClick={copyLink} disabled={!validUrl} aria-label="Copy mobile website address">{copied ? <Check size={16} /> : <Copy size={16} />}</button></div>
      <small className="mobile-access-help">Find your PC’s IPv4 address with <code>ipconfig</code>, then replace the example address above.</small>
      <small className="mobile-access-help">The QR image is generated by QR Server using this link.</small>
      <div className="mobile-access-footer">{isAndroid && !androidDownloadUrl ? 'No APK download is configured yet; this QR opens the web scanner.' : isIos && !iosDownloadUrl ? 'iPhone cannot install an Android APK. Configure an App Store or TestFlight link, or use the web scanner.' : 'Android APKs need a hosted download link. iPhone installs use the App Store or TestFlight; iOS does not install APK files.'}</div>
    </section>
  </div>;
}
